import assert from 'node:assert/strict';
import { normalizeTimelineMarks, getTimelineMarks } from '../services/playback/timelineMarks.js';
import { SeekThumbnailCache, thumbnailBucket } from '../services/playback/seekThumbnails.js';
const context = { type: 'tv', tmdbId: 1396, season: 1, episode: 1, duration: 3600 };
assert.deepEqual(normalizeTimelineMarks({ tmdb_id: 1396, type: 'tv', intro: [{ start_ms: null, end_ms: 90000 }], credits: [{ start_ms: 3540000, end_ms: null }] }, context), [
  { kind: 'intro', start: 0, end: 90 }, { kind: 'credits', start: 3540, end: 3600 },
]);
assert.deepEqual(normalizeTimelineMarks({ tmdb_id: 7, intro: [{ end_ms: 90000 }] }, context), []);
assert.deepEqual(normalizeTimelineMarks({ episode: 2, intro: [{ end_ms: 90000 }] }, context), []);
assert.deepEqual(normalizeTimelineMarks({ credits: [null, {}, [], { start_ms: null, end_ms: null }, { start_ms: '0', end_ms: 3600000 }] }, context), [], 'malformed credits must never offer to skip the entire film');
assert.deepEqual(normalizeTimelineMarks({ intro: [{ start_ms: -1, end_ms: 1 }, { end_ms: 2000000 }, { end_ms: 'NaN' }], credits: [{ start_ms: 3599000, end_ms: 3700000 }] }, context), []);
let lookups = 0;
const fetchImpl = async url => {
  lookups++;
  assert.equal(url.origin, 'https://api.theintrodb.org');
  assert.equal(url.searchParams.get('duration_ms'), '3600000');
  assert.equal(url.searchParams.get('episode'), '1');
  return { ok: true, status: 200, text: async () => JSON.stringify({ intro: [{ start_ms: 20000, end_ms: 90000 }] }) };
};
assert.equal((await getTimelineMarks(context, { fetchImpl })).length, 1);
await getTimelineMarks(context, { fetchImpl });
assert.equal(lookups, 1, 'window rebuilds reuse the same release-specific timestamps');
assert.deepEqual(await getTimelineMarks({ ...context, tmdbId: 100 }, { fetchImpl: async () => { throw Error('offline'); } }), []);
assert.equal(thumbnailBucket(19.9, 3600), 10);
assert.equal(thumbnailBucket(3600, 3600), null);
assert.equal(thumbnailBucket(-1, 3600), null);
assert.equal(thumbnailBucket(0, NaN), null);
let calls = 0, release;
const cache = new SeekThumbnailCache({ maxBytes: 10, maxEntries: 2, extract: async () => { calls++; await new Promise(resolve => { release = resolve; }); return Buffer.from([255,216,1,2,255,217]); } });
const request = { infoHash: 'abc', fileId: 0, at: 15, duration: 3600, getUrl: async () => 'private-provider-url' };
const first = cache.get(request), same = cache.get({ ...request, at: 19 });
assert.equal(await cache.get({ ...request, fileId: 2 }), null, 'another preview cannot spawn a concurrent FFmpeg');
await new Promise(resolve => setImmediate(resolve));
release();
assert.deepEqual(await first, await same);
assert.equal(calls, 1);
await cache.get(request); assert.equal(calls, 1, 'same file and bucket cached');
const other = cache.get({ ...request, fileId: 2 });
await new Promise(resolve => setImmediate(resolve)); release(); await other;
assert.equal(calls, 2, 'a different film in the same pack gets a different frame');
assert.ok(cache.bytes <= 10 && cache.cache.size <= 2, 'memory bound enforced');
let retry = 0;
const failures = new SeekThumbnailCache({ extract: async () => { if (!retry++) throw Error('offline'); return Buffer.from([255,216,255,217]); } });
assert.equal(await failures.get(request), null);
assert.ok(await failures.get(request), 'failed extraction releases capacity and can recover');
assert.equal(failures.pending.size, 0);
let urlCalls = 0;
assert.equal(await failures.get({ ...request, at: Infinity, getUrl: () => { urlCalls++; } }), null);
assert.equal(urlCalls, 0, 'invalid targets never contact the provider');
process.env.MONGODB_URI ||= 'mongodb://127.0.0.1:27017/test';
const { findOwnedPlaybackSession } = await import('../controllers/playbackExtrasController.js');
let query;
const db = { collection: () => ({ findOne: async filter => { query = filter; return null; } }) };
await findOwnedPlaybackSession(db, 'a'.repeat(32), 'owner');
assert.equal(query.userIdStr, 'owner');
assert.ok(query.expiresAt.$gt instanceof Date);
query = null;
assert.equal(await findOwnedPlaybackSession(db, '../secret', 'other'), null);
assert.equal(query, null, 'invalid IDs do not query storage');
console.log('OK optional timestamp lookup, source-isolated previews, bounded concurrency/cache, and owner-only access');
process.exit(0);
